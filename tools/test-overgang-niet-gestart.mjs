import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('overgangsbespreking.html','utf8');
const text=source.slice(source.indexOf('function redenHerstelBlokkade('),source.indexOf('\nlet overgangOpslagBlokkade'));
const check=vm.runInNewContext('('+text.trim()+')');
const pupils=[{id:'actief',start:'2026-09-01',end:'2027-06-30'},{id:'niet-gestart',startNiet:true,start:'2026-09-01',end:'2026-08-31'}];
const dossier={students:[{id:'fiche-actief',schoolbeheerId:'actief',firstName:'Test',lastName:'Actief',readingNote:'Bestaande notitie'},{id:'fiche-oud',schoolbeheerId:'niet-gestart',firstName:'Test',lastName:'Historiek',medicalNote:'Bewaren in de bestaande fiche'}]};
const original=structuredClone(dossier);
assert.equal(check(dossier,pupils,'3A'),'');
assert.deepEqual(dossier,original,'Geen fiche of veld mag worden gewijzigd of verwijderd');
assert.match(check({students:[dossier.students[1]]},pupils,'3A'),/fiches/,'Ontbrekende actieve fiche blijft geblokkeerd');
assert.match(check({students:[...dossier.students,{...dossier.students[1]}]},pupils,'3A'),/dubbele/,'Ook dubbele niet-gestarte fiches blijven geblokkeerd');
assert.match(check({students:[...dossier.students,{id:'vreemd',schoolbeheerId:'onbekend',notes:'Onbekend'}]},pupils,'3A'),/fiches/,'Onbekende fiches worden niet stil genegeerd');
assert.match(check({students:[{...dossier.students[0],readingNote:''},dossier.students[1]]},pupils,'3A'),/notitiecontrole/,'Notitiecontrole van de actieve leerling blijft behouden');
assert.match(check(dossier,[...pupils,pupils[0]],'3A'),/dubbele leerlingcodes/);
console.log('7 controles geslaagd: niet-gestarte fiche behouden, actieve koppelingen en notities gecontroleerd, dubbele of onbekende fiches geweigerd.');
const context=vm.createContext({state:{},centraleNietGestarteIds:new Set(['niet-gestart']),nietActieveOvergangFiches:[],todayISO:()=> '2026-10-21',readSettings:()=>{}});
const apply=source.slice(source.indexOf('function applyProjectData('),source.indexOf('\nasync function loadFirebaseProjectOnStart'));
const collect=source.slice(source.indexOf('function collectProjectData('),source.indexOf('\nasync function saveJSON'));
vm.runInContext(apply+'\n'+collect,context);
context.data=structuredClone(dossier);
vm.runInContext('applyProjectData(data)',context);
assert.equal(context.state.students.length,1);
assert.equal(context.nietActieveOvergangFiches.length,1);
const saved=vm.runInContext('collectProjectData()',context);
assert.equal(saved.students.length,2);
assert.equal(saved.students[1].medicalNote,dossier.students[1].medicalNote);
assert.equal(check(saved,pupils,'3A'),'');
console.log('Actieve klas telt 1 leerling; oude fiche en notities blijven volledig in de opslag bewaard.');
