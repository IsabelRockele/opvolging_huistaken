import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {maakBriefOverzichten} from '../nieuwjaarsbrieven-archief.mjs';
import {maakMaandPdf} from '../maandarchief.js';
const klassen=[{klas:'2A',leerlingen:[{id:'a',first:'Anna'},{id:'b',first:'Bram'},{id:'c',first:'Cato'},{id:'d',first:'Daan'}],brieven:[{id:'a',aantal:0},{id:'b',aantal:null},{id:'d',aantal:3,verwerkt:{aantal:2,bedragCent:120}},{id:'oud',naam:'Oude leerling',aantal:2,verwerkt:{aantal:2,bedragCent:120}}]},{klas:'1A',leerlingen:[]}];
const origineel=JSON.stringify(klassen);
const overzicht=maakBriefOverzichten({klassen});
assert.equal(overzicht[0].klas,'1A');
const rows=overzicht[1].tabellen[0].rijen;
assert.deepEqual(rows[0],['Anna','0','0.00','Geen brieven gewenst']);
assert.equal(rows[1][3],'Nog niet ingevuld');
assert.equal(rows[2][3],'Nog niet ingevuld');
assert.equal(rows[3][3],'Gewijzigd — opnieuw te verwerken');
assert.equal(rows[4][3],'Verwerkt');
assert.match(overzicht[1].notities[1],/3 van 5 ingevuld \| 5 brieven \| Totaal: EUR 3.00/);
assert.equal(maakBriefOverzichten({klassen,prijsCent:70})[1].tabellen[0].rijen[4][3],'Gewijzigd — opnieuw te verwerken');
assert.equal(JSON.stringify(klassen),origineel);
const {jsPDF}=createRequire(import.meta.url)('../jspdf.umd.min.js');
const groot={klas:'3B',leerlingen:Array.from({length:45},(_,i)=>({id:String(i),first:'Leerling '+i,last:i===0?'Van Een Bijzonder Lange Familienaam Voor De Afdrukcontrole':'Voorbeeld'})),brieven:[{id:'0',aantal:5}]};
const pdf=maakMaandPdf(jsPDF,{soort:'nieuwjaarsbrieven',schooljaar:'2026-2027',overzichten:maakBriefOverzichten({klassen:[...klassen,groot]})});
assert.ok(pdf.getNumberOfPages()>=4);
fs.mkdirSync('tmp/pdfs/nieuwjaarsbrieven',{recursive:true});
fs.writeFileSync('tmp/pdfs/nieuwjaarsbrieven/proef.pdf',Buffer.from(pdf.output('arraybuffer')));
console.log('Nieuwjaarsbrieven PDF: lege antwoorden, nul, correcties, oude leerlingen, totalen, prijs en meerdere pagina’s gecontroleerd.');
